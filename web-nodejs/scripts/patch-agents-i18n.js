function patchFile(filePath, langKey) {
    const pack = AGENTS_BY_LANG[langKey] || AGENTS_BY_LANG.en;
    const raw = fs.readFileSync(filePath, 'utf8');
    const data = JSON.parse(raw);
    data.nav = data.nav || {};
    data.nav.agents = pack.nav;
    // Keep old key as alias for any leftover references
    data.nav.generator = pack.nav;
    data.dashboard = data.dashboard || {};
    data.dashboard.open_agents = pack.open;
    data.dashboard.agents_hint = pack.hint;
    data.dashboard.open_generator = pack.open;
    data.dashboard.generate_config = pack.hint;
    data.agents = pack.agents;
    fs.writeFileSync(filePath, `${JSON.stringify(data, null, 4)}\n`, 'utf8');
}

const files = fs.readdirSync(LANG_DIR).filter((f) => f.endsWith('.json'));
for (const file of files) {
    const langKey = file.replace(/\.json$/, '');
    patchFile(path.join(LANG_DIR, file), langKey);
    console.log(`patched ${file}`);
}
console.log(`done: ${files.length} locales`);
